//! Process and native window composition. Features request windows through events.
use crate::project::incoming::{self, Inbox};
use crate::workspace::view::{Studio, WindowRequest, actions::*};
use gpui_kit::*;
use std::{cell::RefCell, rc::Rc, time::Duration};
#[cfg(target_os = "macos")]
mod macos_quit;

pub(crate) fn open_studio(path: Option<std::path::PathBuf>, cx: &mut App) -> anyhow::Result<()> {
    let options = WindowOptions {
        window_bounds: Some(WindowBounds::Windowed(Bounds::centered(
            None,
            size(px(1200.), px(850.)),
            cx,
        ))),
        window_min_size: Some(size(px(600.), px(500.))),
        // Match the irodoru.desktop entry generated by cargo-packager (Wayland/X11).
        app_id: Some("irodoru".into()),
        #[cfg(target_os = "linux")]
        icon: Some(std::sync::Arc::new(
            image::load_from_memory_with_format(
                include_bytes!("../../icons/128x128.png"),
                image::ImageFormat::Png,
            )?
            .into_rgba8(),
        )),
        titlebar: cfg!(target_os = "macos").then(TitlebarOptions::default),
        window_decorations: if cfg!(target_os = "macos") {
            None
        } else {
            Some(WindowDecorations::Client)
        },
        app_owns_titlebar_drag: !cfg!(target_os = "macos"),
        ..Default::default()
    };
    gpui_kit::open_window(options, cx, move |window, cx| {
        window.set_window_title("irodoru");
        let studio = cx.new(|cx| Studio::new(path, window, cx));
        cx.subscribe(&studio, |studio, request, cx| match request {
            WindowRequest::New => {
                if let Err(error) = open_studio(None, cx) {
                    studio.update(cx, |studio, cx| studio.report_error(error.to_string(), cx));
                }
            }
        })
        .detach();
        studio
    })?;
    cx.activate(true);
    Ok(())
}
pub fn run() {
    let paths = incoming::argument_paths(
        std::env::args_os(),
        &std::env::current_dir().unwrap_or_default(),
    );
    let inbox = match Inbox::new() {
        Ok(inbox) => inbox,
        Err(error) => {
            show_error(error);
            return;
        }
    };
    let _instance = match crate::preferences::lock_instance() {
        Ok(lock) => lock,
        Err(error) => {
            if !paths.is_empty()
                && matches!(
                    error.downcast_ref::<std::fs::TryLockError>(),
                    Some(std::fs::TryLockError::WouldBlock)
                )
            {
                if let Err(error) = inbox.forward(&paths) {
                    show_error(error);
                }
            } else {
                show_error(error);
            }
            return;
        }
    };
    let pending = Rc::new(RefCell::new(paths));
    let application = gpui_kit::application();
    let opened = pending.clone();
    application.on_open_urls(move |urls| opened.borrow_mut().extend(incoming::url_paths(urls)));
    application.run(move |cx| {
        gpui_kit::init(cx);
        if let Err(error) = crate::preferences::theme::initialize(cx) {
            eprintln!("{error:#}");
            cx.quit();
            return;
        }
        cx.on_window_closed(|cx, _| {
            if cx.windows().is_empty() {
                #[cfg(target_os = "macos")]
                macos_quit::allow_exit();
                cx.quit();
            }
        })
        .detach();
        let [q, w, nw, n, o, s, prefs] = if cfg!(target_os = "macos") {
            [
                "cmd-q",
                "cmd-w",
                "cmd-shift-n",
                "cmd-n",
                "cmd-o",
                "cmd-s",
                "cmd-,",
            ]
        } else {
            [
                "ctrl-q",
                "ctrl-w",
                "ctrl-shift-n",
                "ctrl-n",
                "ctrl-o",
                "ctrl-s",
                "ctrl-,",
            ]
        };
        cx.bind_keys([
            KeyBinding::new("tab", MenuNext, Some("AppMenu")),
            KeyBinding::new("shift-tab", MenuPrevious, Some("AppMenu")),
            KeyBinding::new(q, Quit, None),
            KeyBinding::new(w, CloseWindow, None),
            KeyBinding::new(nw, NewWindow, None),
            KeyBinding::new(n, NewProject, None),
            KeyBinding::new(o, OpenProject, None),
            KeyBinding::new(s, SaveProject, None),
            KeyBinding::new(prefs, Preferences, None),
        ]);
        cx.set_menus(vec![Menu {
            disabled: false,
            name: "irodoru".into(),
            items: vec![
                MenuItem::action("新規ウィンドウ", NewWindow),
                MenuItem::action("新規プロジェクト…", NewProject),
                MenuItem::action("プロジェクトを開く…", OpenProject),
                MenuItem::action("プロジェクトを保存", SaveProject),
                MenuItem::action("環境設定…", Preferences),
                MenuItem::action("ウィンドウを閉じる", CloseWindow),
            ],
        }]);
        let paths = std::mem::take(&mut *pending.borrow_mut());
        if paths.is_empty() {
            if let Err(error) = open_studio(None, cx) {
                show_error(error);
                cx.quit();
                return;
            }
        } else {
            open_projects(paths, cx);
        }
        #[cfg(target_os = "macos")]
        macos_quit::install(cx);
        cx.spawn(async move |cx| {
            loop {
                cx.background_executor()
                    .timer(Duration::from_millis(250))
                    .await;
                let inbox = inbox.clone();
                let forwarded = cx
                    .background_executor()
                    .spawn(async move { inbox.drain() })
                    .await;
                let mut paths = std::mem::take(&mut *pending.borrow_mut());
                match forwarded {
                    Ok(batch) => paths.extend(batch),
                    Err(error) => {
                        // Do not show a repeating modal if a user's configuration disk disappears.
                        eprintln!("プロジェクトを開く要求を読み込めません: {error:#}");
                    }
                }
                if !paths.is_empty() {
                    cx.update(|cx| open_projects(paths, cx));
                }
            }
        })
        .detach();
    });
}

fn open_projects(paths: Vec<std::path::PathBuf>, cx: &mut App) {
    let mut seen = std::collections::HashSet::new();
    for path in paths {
        if !seen.insert(path.canonicalize().unwrap_or_else(|_| path.clone())) {
            continue;
        }
        // OS requests get independent windows. Existing editors, drafts, synthesis jobs and
        // failed saves stay intact; WindowProject still prevents two writers for one archive.
        if let Err(error) = open_studio(Some(path), cx) {
            show_error(error);
        }
    }
}

fn show_error(error: anyhow::Error) {
    rfd::MessageDialog::new()
        .set_title("irodoru")
        .set_description(format!("{error:#}"))
        .show();
}
