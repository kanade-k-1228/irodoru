//! Process and native window composition. Features request windows through events.
use crate::workspace::view::{Studio, WindowRequest};
use gpui_kit::*;
#[cfg(target_os = "macos")]
pub mod macos;
mod placement;

pub struct SharedInference(pub Result<std::sync::Arc<crate::synthesis::Inference>, String>);
impl Global for SharedInference {}

pub fn start_inference() -> anyhow::Result<std::sync::Arc<crate::synthesis::Inference>> {
    use crate::{
        preferences::ModelSettings,
        synthesis::{Inference, resources},
    };
    let settings = ModelSettings::load()?;
    Ok(std::sync::Arc::new(Inference::start_configured(
        settings,
        |directory, progress| {
            Ok(irodoru_engine::EngineConfig::anime(
                resources::models_with_directory(directory, progress)?,
            ))
        },
        |settings| settings.save(),
    )?))
}

pub fn open_studio(path: Option<std::path::PathBuf>, cx: &mut App) -> anyhow::Result<()> {
    let placement = placement::restore(cx);
    let options = WindowOptions {
        window_bounds: placement.map(|(bounds, _)| bounds).or_else(|| {
            cx.windows()
                .is_empty()
                .then(|| WindowBounds::centered(size(px(960.), px(700.)), cx))
        }),
        display_id: placement.map(|(_, display)| display),
        window_min_size: Some(size(px(600.), px(500.))),
        // Match the irodoru.desktop entry generated by cargo-packager (Wayland/X11).
        app_id: Some("irodoru".into()),
        #[cfg(target_os = "linux")]
        icon: Some(std::sync::Arc::new(
            image::load_from_memory_with_format(
                include_bytes!("../../icons/128x128.png"),
                image::ImageFormat::Png,
            )?
            .into_rgba8(),
        )),
        titlebar: cfg!(target_os = "macos").then(TitlebarOptions::default),
        window_decorations: if cfg!(target_os = "macos") {
            None
        } else {
            Some(WindowDecorations::Client)
        },
        app_owns_titlebar_drag: !cfg!(target_os = "macos"),
        ..Default::default()
    };
    gpui_kit::open_window(options, cx, move |window, cx| {
        window.set_window_title("irodoru");
        let inference = cx.global::<SharedInference>().0.clone();
        let studio = cx.new(|cx| {
            placement::remember(window, cx);
            Studio::new(path, inference, window, cx)
        });
        cx.subscribe(&studio, |studio, request, cx| match request {
            WindowRequest::New => {
                if let Err(error) = open_studio(None, cx) {
                    studio.update(cx, |studio, cx| studio.report_error(error.to_string(), cx));
                }
            }
        })
        .detach();
        studio
    })?;
    cx.activate(true);
    Ok(())
}
pub fn open_projects(paths: Vec<std::path::PathBuf>, cx: &mut App) {
    let mut seen = std::collections::HashSet::new();
    for path in paths {
        if !seen.insert(path.canonicalize().unwrap_or_else(|_| path.clone())) {
            continue;
        }
        // OS requests get independent windows. Existing editors, synthesis jobs and
        // failed saves stay intact; WindowProject still prevents two writers for one archive.
        if let Err(error) = open_studio(Some(path), cx) {
            show_error(error);
        }
    }
}

pub fn show_error(error: anyhow::Error) {
    rfd::MessageDialog::new()
        .set_title("irodoru")
        .set_description(format!("{error:#}"))
        .show();
}
