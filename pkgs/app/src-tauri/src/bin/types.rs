use irodoru_desktop::{
    library::{Character, CharacterInput, Take},
    types::*,
};
use ts_rs::{Config, TS};
fn main() {
    let config = Config::default();
    println!("// Generated by pnpm generate app-types. Do not edit.");
    for declaration in [
        Character::decl(&config),
        CharacterInput::decl(&config),
        Take::decl(&config),
        GenerationSettings::decl(&config),
        ScriptRow::decl(&config),
        EditorState::decl(&config),
        SynthesisInput::decl(&config),
        TakeRequest::decl(&config),
        InferenceStatus::decl(&config),
        irodoru_desktop::project::ProjectStatus::decl(&config),
    ] {
        let declaration = declaration
            .lines()
            .map(str::trim_end)
            .collect::<Vec<_>>()
            .join("\n");
        println!("export {declaration}");
    }
}
