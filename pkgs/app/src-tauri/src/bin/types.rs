use irodoru_desktop::{
    library::{Character, CharacterInput, Take},
    types::*,
};
use ts_rs::TS;
fn main() {
    println!("// Generated by pnpm generate app-types. Do not edit.");
    for declaration in [
        Character::decl(),
        CharacterInput::decl(),
        Take::decl(),
        GenerationSettings::decl(),
        ScriptRow::decl(),
        EditorState::decl(),
        SynthesisInput::decl(),
        TakeRequest::decl(),
        InferenceStatus::decl(),
        irodoru_desktop::project::ProjectStatus::decl(),
    ] {
        let declaration = declaration
            .lines()
            .map(str::trim_end)
            .collect::<Vec<_>>()
            .join("\n");
        println!("export {declaration}");
    }
}
